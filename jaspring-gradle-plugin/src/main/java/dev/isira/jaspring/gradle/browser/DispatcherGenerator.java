package dev.isira.jaspring.gradle.browser;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/// Writes the Java entry point of the WebAssembly module: `main` installs the dispatcher, which switches on the
/// closure id, decodes the captured values, runs the lambda and encodes the result. Decoders and encoders are
/// generated per record and enum, so nothing in the image is reflective.
public final class DispatcherGenerator {

    public static final String PACKAGE = "dev.isira.jaspring.browser.generated";
    public static final String CLASS_NAME = "JaspringWasmEntry";
    public static final String MAIN_CLASS = PACKAGE + "." + CLASS_NAME;

    private final StringBuilder out = new StringBuilder();
    private final Map<String, String> decoders = new LinkedHashMap<>();
    private final Map<String, String> encoders = new LinkedHashMap<>();
    private final StringBuilder helpers = new StringBuilder();

    private DispatcherGenerator() {
    }

    public static String generate(List<FoundClosure> closures) {
        return new DispatcherGenerator().write(closures);
    }

    private String write(List<FoundClosure> closures) {
        out.append("package ").append(PACKAGE).append(";\n\n");
        out.append("import org.graalvm.webimage.api.JSObject;\n");
        out.append("import dev.isira.jaspring.browser.runtime.Decoders;\n");
        out.append("import dev.isira.jaspring.browser.runtime.Encoders;\n");
        out.append("import dev.isira.jaspring.browser.runtime.Results;\n");
        out.append("import dev.isira.jaspring.browser.runtime.WasmBridge;\n");
        out.append("import dev.isira.jaspring.browser.runtime.WebClient;\n\n");
        out.append("/// Generated by the Jaspring Gradle plugin; do not edit.\n");
        out.append("public final class ").append(CLASS_NAME).append(" {\n\n");
        out.append("    public static void main(String[] args) {\n");
        out.append("        WasmBridge.install(").append(CLASS_NAME).append("::run);\n");
        out.append("    }\n\n");
        out.append("    static JSObject run(JSObject request) {\n");
        out.append("        final String id = Decoders.string(request, \"id\");\n");
        out.append("        final String host = Decoders.string(request, \"host\");\n");
        out.append("        final JSObject args = Decoders.object(request, \"args\");\n");
        out.append("        try {\n");
        out.append("            switch (id) {\n");
        for (final var closure : closures) {
            out.append("                case \"").append(closure.id()).append("\": {\n");
            final var arguments = new StringBuilder();
            for (var i = 0; i < closure.captured().size(); i++) {
                final var shape = closure.captured().get(i);
                out.append("                    final ").append(TypeNames.javaSource(shape.sourceName())).append(" a").append(i)
                        .append(" = ").append(decodeExpression(shape, "args", "\"" + i + "\"")).append(";\n");
                arguments.append("a").append(i).append(", ");
            }
            final var call = TypeNames.javaSource(closure.implClass()) + "." + closure.implMethod() + "(" + arguments + "WebClient.forHost(host))";
            if (closure.promise()) {
                out.append("                    return Results.promise(").append(call).append(", value -> ")
                        .append(boxedExpression(closure.returnShape(), "(" + TypeNames.javaSource(closure.returnType()) + ") value")).append(");\n");
            } else {
                out.append("                    return Results.value(").append(boxedExpression(closure.returnShape(), call)).append(");\n");
            }
            out.append("                }\n");
        }
        out.append("                default:\n");
        out.append("                    return Results.error(\"unknown closure \" + id + \"; the page and the WebAssembly build disagree\");\n");
        out.append("            }\n");
        out.append("        } catch (Throwable t) {\n");
        out.append("            return Results.error(t.toString());\n");
        out.append("        }\n");
        out.append("    }\n");
        out.append(helpers);
        out.append("}\n");
        return out.toString();
    }

    // ---- decoding: JSObject container + key -> Java value ----

    private String decodeExpression(TypeShapes.Shape shape, String container, String key) {
        return switch (shape) {
            case TypeShapes.Scalar scalar -> scalarDecode(scalar.sourceName(), container, key);
            case TypeShapes.EnumShape enumShape -> "(Decoders.isNull(" + container + ", " + key + ") ? null : "
                    + TypeNames.javaSource(enumShape.sourceName()) + ".valueOf(Decoders.string(" + container + ", " + key + ")))";
            case TypeShapes.RecordShape record -> recordDecoder(record) + "(Decoders.object(" + container + ", " + key + "))";
            case TypeShapes.ArrayShape array -> arrayDecoder(array) + "(Decoders.object(" + container + ", " + key + "))";
            case TypeShapes.ListShape list -> listDecoder(list) + "(Decoders.object(" + container + ", " + key + "))";
            case TypeShapes.MapShape map -> mapDecoder(map) + "(Decoders.object(" + container + ", " + key + "))";
            case TypeShapes.OptionalShape optional -> "java.util.Optional.ofNullable(" + decodeExpression(optional.value(), container, key) + ")";
        };
    }

    private static String scalarDecode(String type, String container, String key) {
        final var nullable = "Decoders.isNull(" + container + ", " + key + ") ? null : ";
        return switch (type) {
            case "int" -> "Decoders.integer(" + container + ", " + key + ")";
            case "long" -> "Decoders.longValue(" + container + ", " + key + ")";
            case "double" -> "Decoders.doubleValue(" + container + ", " + key + ")";
            case "float" -> "(float) Decoders.doubleValue(" + container + ", " + key + ")";
            case "short" -> "(short) Decoders.integer(" + container + ", " + key + ")";
            case "byte" -> "(byte) Decoders.integer(" + container + ", " + key + ")";
            case "char" -> "Decoders.string(" + container + ", " + key + ").charAt(0)";
            case "boolean" -> "Decoders.bool(" + container + ", " + key + ")";
            case "java.lang.Integer" -> "(" + nullable + "Integer.valueOf(Decoders.integer(" + container + ", " + key + ")))";
            case "java.lang.Long" -> "(" + nullable + "Long.valueOf(Decoders.longValue(" + container + ", " + key + ")))";
            case "java.lang.Double" -> "(" + nullable + "Double.valueOf(Decoders.doubleValue(" + container + ", " + key + ")))";
            case "java.lang.Float" -> "(" + nullable + "Float.valueOf((float) Decoders.doubleValue(" + container + ", " + key + ")))";
            case "java.lang.Short" -> "(" + nullable + "Short.valueOf((short) Decoders.integer(" + container + ", " + key + ")))";
            case "java.lang.Byte" -> "(" + nullable + "Byte.valueOf((byte) Decoders.integer(" + container + ", " + key + ")))";
            case "java.lang.Character" -> "(" + nullable + "Character.valueOf(Decoders.string(" + container + ", " + key + ").charAt(0)))";
            case "java.lang.Boolean" -> "(" + nullable + "Boolean.valueOf(Decoders.bool(" + container + ", " + key + ")))";
            case "java.lang.String" -> "(" + nullable + "Decoders.string(" + container + ", " + key + "))";
            default -> "null";
        };
    }

    private String recordDecoder(TypeShapes.RecordShape record) {
        return helper(decoders, "record:" + record.sourceName(), name -> {
            final var type = TypeNames.javaSource(record.sourceName());
            final var body = new StringBuilder();
            body.append("\n    static ").append(type).append(" ").append(name).append("(JSObject o) {\n");
            body.append("        if (o == null) return null;\n");
            body.append("        return new ").append(type).append("(");
            for (var i = 0; i < record.components().size(); i++) {
                final var component = record.components().get(i);
                if (i > 0) body.append(",\n                ");
                body.append(decodeExpression(component.shape(), "o", "\"" + component.name() + "\""));
            }
            body.append(");\n    }\n");
            return body.toString();
        });
    }

    private String arrayDecoder(TypeShapes.ArrayShape array) {
        return helper(decoders, "array:" + array.sourceName(), name -> {
            final var element = TypeNames.javaSource(array.element().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static ").append(element).append("[] ").append(name).append("(JSObject a) {\n");
            body.append("        if (a == null) return null;\n");
            body.append("        final ").append(element).append("[] out = new ").append(element).append("[Decoders.length(a)];\n");
            body.append("        for (int i = 0; i < out.length; i++) out[i] = ").append(decodeExpression(array.element(), "a", "Decoders.index(i)")).append(";\n");
            body.append("        return out;\n    }\n");
            return body.toString();
        });
    }

    private String listDecoder(TypeShapes.ListShape list) {
        return helper(decoders, "list:" + list.element().sourceName(), name -> {
            final var element = boxedName(list.element().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static java.util.List<").append(element).append("> ").append(name).append("(JSObject a) {\n");
            body.append("        if (a == null) return null;\n");
            body.append("        final java.util.ArrayList<").append(element).append("> out = new java.util.ArrayList<>();\n");
            body.append("        for (int i = 0; i < Decoders.length(a); i++) out.add(").append(decodeExpression(list.element(), "a", "Decoders.index(i)")).append(");\n");
            body.append("        return java.util.Collections.unmodifiableList(out);\n    }\n");
            return body.toString();
        });
    }

    private String mapDecoder(TypeShapes.MapShape map) {
        return helper(decoders, "map:" + map.value().sourceName(), name -> {
            final var value = boxedName(map.value().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static java.util.Map<String, ").append(value).append("> ").append(name).append("(JSObject o) {\n");
            body.append("        if (o == null) return null;\n");
            body.append("        final java.util.LinkedHashMap<String, ").append(value).append("> out = new java.util.LinkedHashMap<>();\n");
            body.append("        final JSObject keys = Decoders.keys(o);\n");
            body.append("        for (int i = 0; i < Decoders.length(keys); i++) {\n");
            body.append("            final String key = Decoders.string(keys, Decoders.index(i));\n");
            body.append("            out.put(key, ").append(decodeExpression(map.value(), "o", "key")).append(");\n");
            body.append("        }\n        return java.util.Collections.unmodifiableMap(out);\n    }\n");
            return body.toString();
        });
    }

    // ---- encoding: Java value -> boxed JSObject ({v: ...}) ----

    private String boxedExpression(TypeShapes.Shape shape, String value) {
        return switch (shape) {
            case TypeShapes.Scalar scalar -> scalarBoxed(scalar.sourceName(), value);
            case TypeShapes.EnumShape ignored -> "Encoders.boxedName(" + value + ")";
            case TypeShapes.RecordShape record -> "Encoders.boxed(" + recordEncoder(record) + "(" + value + "))";
            case TypeShapes.ArrayShape array -> "Encoders.boxed(" + arrayEncoder(array) + "(" + value + "))";
            case TypeShapes.ListShape list -> "Encoders.boxed(" + listEncoder(list) + "(" + value + "))";
            case TypeShapes.MapShape map -> "Encoders.boxed(" + mapEncoder(map) + "(" + value + "))";
            case TypeShapes.OptionalShape optional -> optionalEncoder(optional) + "(" + value + ")";
        };
    }

    private static String scalarBoxed(String type, String value) {
        return switch (type) {
            case "int", "long", "double", "float", "short", "byte" -> "Encoders.boxed((double) (" + value + "))";
            case "char" -> "Encoders.boxed(String.valueOf(" + value + "))";
            case "boolean" -> "Encoders.boxed(" + value + ")";
            case "void", "java.lang.Void" -> "Encoders.boxedNull()";
            case "java.lang.Character" -> "Encoders.boxedCharacter(" + value + ")";
            case "java.lang.Boolean" -> "Encoders.boxedBoolean(" + value + ")";
            case "java.lang.String" -> "Encoders.boxedString(" + value + ")";
            default -> "Encoders.boxedNumber(" + value + ")";
        };
    }

    /// Sets `value` of `shape` on `target[key]`, inside a generated encoder.
    private String setStatement(TypeShapes.Shape shape, String target, String key, String value) {
        return switch (shape) {
            case TypeShapes.Scalar scalar -> "Encoders.setBoxed(" + target + ", " + key + ", " + scalarBoxed(scalar.sourceName(), value) + ");";
            case TypeShapes.EnumShape ignored -> "Encoders.setBoxed(" + target + ", " + key + ", Encoders.boxedName(" + value + "));";
            case TypeShapes.RecordShape record -> "Encoders.setBoxed(" + target + ", " + key + ", Encoders.boxed(" + recordEncoder(record) + "(" + value + ")));";
            case TypeShapes.ArrayShape array -> "Encoders.setBoxed(" + target + ", " + key + ", Encoders.boxed(" + arrayEncoder(array) + "(" + value + ")));";
            case TypeShapes.ListShape list -> "Encoders.setBoxed(" + target + ", " + key + ", Encoders.boxed(" + listEncoder(list) + "(" + value + ")));";
            case TypeShapes.MapShape map -> "Encoders.setBoxed(" + target + ", " + key + ", Encoders.boxed(" + mapEncoder(map) + "(" + value + ")));";
            case TypeShapes.OptionalShape optional -> "Encoders.setBoxed(" + target + ", " + key + ", " + optionalEncoder(optional) + "(" + value + "));";
        };
    }

    private String recordEncoder(TypeShapes.RecordShape record) {
        return helper(encoders, "record:" + record.sourceName(), name -> {
            final var type = TypeNames.javaSource(record.sourceName());
            final var body = new StringBuilder();
            body.append("\n    static JSObject ").append(name).append("(").append(type).append(" r) {\n");
            body.append("        if (r == null) return null;\n");
            body.append("        final JSObject o = Encoders.object();\n");
            for (final var component : record.components()) {
                body.append("        ").append(setStatement(component.shape(), "o", "\"" + component.name() + "\"", "r." + component.name() + "()")).append("\n");
            }
            body.append("        return o;\n    }\n");
            return body.toString();
        });
    }

    private String arrayEncoder(TypeShapes.ArrayShape array) {
        return helper(encoders, "array:" + array.sourceName(), name -> {
            final var element = TypeNames.javaSource(array.element().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static JSObject ").append(name).append("(").append(element).append("[] values) {\n");
            body.append("        if (values == null) return null;\n");
            body.append("        final JSObject a = Encoders.array();\n");
            body.append("        for (int i = 0; i < values.length; i++) ").append(setStatement(array.element(), "a", "Decoders.index(i)", "values[i]")).append("\n");
            body.append("        return a;\n    }\n");
            return body.toString();
        });
    }

    private String listEncoder(TypeShapes.ListShape list) {
        return helper(encoders, "list:" + list.element().sourceName(), name -> {
            final var element = boxedName(list.element().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static JSObject ").append(name).append("(java.util.List<").append(element).append("> values) {\n");
            body.append("        if (values == null) return null;\n");
            body.append("        final JSObject a = Encoders.array();\n");
            body.append("        for (int i = 0; i < values.size(); i++) ").append(setStatement(list.element(), "a", "Decoders.index(i)", "values.get(i)")).append("\n");
            body.append("        return a;\n    }\n");
            return body.toString();
        });
    }

    private String mapEncoder(TypeShapes.MapShape map) {
        return helper(encoders, "map:" + map.value().sourceName(), name -> {
            final var value = boxedName(map.value().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static JSObject ").append(name).append("(java.util.Map<String, ").append(value).append("> values) {\n");
            body.append("        if (values == null) return null;\n");
            body.append("        final JSObject o = Encoders.object();\n");
            body.append("        for (java.util.Map.Entry<String, ").append(value).append("> e : values.entrySet()) ")
                    .append(setStatement(map.value(), "o", "e.getKey()", "e.getValue()")).append("\n");
            body.append("        return o;\n    }\n");
            return body.toString();
        });
    }

    private String optionalEncoder(TypeShapes.OptionalShape optional) {
        return helper(encoders, "optional:" + optional.value().sourceName(), name -> {
            final var value = boxedName(optional.value().sourceName());
            final var body = new StringBuilder();
            body.append("\n    static JSObject ").append(name).append("(java.util.Optional<").append(value).append("> value) {\n");
            body.append("        if (value == null || value.isEmpty()) return Encoders.boxedNull();\n");
            body.append("        return ").append(boxedExpression(optional.value(), "value.get()")).append(";\n    }\n");
            return body.toString();
        });
    }

    /// Registers the helper's name before generating its body, because bodies recurse into other helpers.
    private String helper(Map<String, String> registry, String key, java.util.function.Function<String, String> body) {
        final var existing = registry.get(key);
        if (existing != null) return existing;
        final var name = (registry == decoders ? "decode" : "encode") + registry.size();
        registry.put(key, name);
        helpers.append(body.apply(name));
        return name;
    }

    private static String boxedName(String sourceName) {
        return switch (sourceName) {
            case "int" -> "Integer";
            case "long" -> "Long";
            case "double" -> "Double";
            case "float" -> "Float";
            case "short" -> "Short";
            case "byte" -> "Byte";
            case "char" -> "Character";
            case "boolean" -> "Boolean";
            default -> TypeNames.javaSource(sourceName);
        };
    }
}
