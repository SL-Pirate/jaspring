import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const versions = {
  angular: require('@angular/compiler/package.json').version,
  postcss: require('postcss/package.json').version,
  tailwind: require('tailwindcss/package.json').version,
};

// platform "browser" honours PostCSS's browser field, which drops its Node-only modules (path, url, fs, source maps).
const result = await build({
  entryPoints: ['src/entry.mjs'],
  outfile: '../../jaspring-core/src/main/resources/jaspring/js/jaspring-compiler.mjs',
  bundle: true,
  metafile: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  // Java identifies AST nodes by constructor.name, so names must survive minification.
  keepNames: true,
  treeShaking: true,
  // Tailwind's own stylesheets are bundled as strings and served to its @import loader.
  loader: { '.css': 'text' },
  define: {
    'process.env.NODE_ENV': '"production"',
    __JASPRING_VERSIONS__: JSON.stringify(versions),
  },
  banner: { js: `/* jaspring-compiler bundle. @angular/compiler ${versions.angular}, postcss ${versions.postcss}, tailwindcss ${versions.tailwind}. Generated by tools/js-bundle; do not edit. */` },
  logLevel: 'info',
});

// Preserve complete licenses for packages whose code actually ships in the bundle.
const licenses = new Map();
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, contribution] of Object.entries(output.inputs)) {
    if (!input.startsWith('node_modules/') || contribution.bytesInOutput === 0) continue;
    let directory = dirname(resolve(input));
    let pkg;
    while (true) {
      const manifest = join(directory, 'package.json');
      if (existsSync(manifest)) {
        pkg = JSON.parse(readFileSync(manifest, 'utf8'));
        if (pkg.name && pkg.version) break;
      }
      const parent = dirname(directory);
      if (parent === directory) throw new Error(`No package.json for bundled input ${input}`);
      directory = parent;
    }
    const key = `${pkg.name} ${pkg.version}`;
    if (licenses.has(key)) continue;
    const license = ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'license']
      .map(name => join(directory, name)).find(existsSync);
    if (!license) throw new Error(`No license file for bundled package ${key}`);
    licenses.set(key, readFileSync(license, 'utf8').trim());
  }
}
const notices = '../../jaspring-core/src/main/resources/META-INF/jaspring/THIRD-PARTY-LICENSES.txt';
mkdirSync(dirname(notices), { recursive: true });
writeFileSync(notices, 'Generated by tools/js-bundle. Licenses for code bundled in jaspring-compiler.mjs.\n\n'
  + [...licenses].sort(([a], [b]) => a.localeCompare(b))
    .map(([name, license]) => `${name}\n${'='.repeat(name.length)}\n\n${license}\n`).join('\n'));
