import { build } from "esbuild";
import { createRequire } from "node:module";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import typescriptLibs from "./src/typescript-libs-plugin.mjs";
import { options as typescriptOptions } from "./src/typescript-options.mjs";

const require = createRequire(import.meta.url);
const versions = {
  angular: require("@angular/compiler/package.json").version,
  postcss: require("postcss/package.json").version,
  tailwind: require("tailwindcss/package.json").version,
  typescript: require("typescript/package.json").version,
};

// ---------- jaspring-compiler: Angular's compiler, PostCSS and Tailwind for jaspring-core ----------

// platform "browser" honours PostCSS's browser field, which drops its Node-only modules (path, url, fs, source maps).
const compiler = await build({
  entryPoints: ["src/entry.mjs"],
  outfile:
    "../../jaspring-core/src/main/resources/jaspring/js/jaspring-compiler.mjs",
  bundle: true,
  metafile: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  // Java identifies AST nodes by constructor.name, so names must survive minification.
  keepNames: true,
  treeShaking: true,
  // Tailwind's own stylesheets are bundled as strings and served to its @import loader.
  loader: { ".css": "text" },
  define: {
    "process.env.NODE_ENV": '"production"',
    __JASPRING_VERSIONS__: JSON.stringify({
      angular: versions.angular,
      postcss: versions.postcss,
      tailwind: versions.tailwind,
    }),
  },
  banner: {
    js: `/* jaspring-compiler bundle. @angular/compiler ${versions.angular}, postcss ${versions.postcss}, tailwindcss ${versions.tailwind}. Generated by tools/js-bundle; do not edit. */`,
  },
  logLevel: "info",
});
writeNotices(
  "../../jaspring-core/src/main/resources/META-INF/jaspring/THIRD-PARTY-LICENSES.txt",
  "jaspring-compiler.mjs",
  collectLicenses(compiler.metafile),
);

// ---------- jaspring-typescript: the TypeScript compiler for jaspring-typescript ----------

// TypeScript's browser field stubs fs, os, path and friends; `process.browser` keeps ts.sys undefined under Node too,
// so the in-memory host in src/typescript.mjs is the only host on both runtimes.
const typescriptOutfile =
  "../../jaspring-typescript/src/main/resources/jaspring/typescript/jaspring-typescript.mjs";
const typescript = await build({
  entryPoints: ["src/typescript.mjs"],
  outfile: typescriptOutfile,
  bundle: true,
  metafile: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  treeShaking: true,
  plugins: [typescriptLibs(typescriptOptions.lib)],
  define: {
    "process.env.NODE_ENV": '"production"',
    "process.browser": "true",
    __JASPRING_VERSIONS__: JSON.stringify({ typescript: versions.typescript }),
  },
  banner: {
    js: `/* jaspring-typescript bundle. typescript ${versions.typescript}. Generated by tools/js-bundle; do not edit. */`,
  },
  logLevel: "info",
});
const typescriptLicenses = collectLicenses(typescript.metafile);
const notice = join(
  dirname(require.resolve("typescript/package.json")),
  "ThirdPartyNoticeText.txt",
);
typescriptLicenses.set(
  "typescript third-party notices",
  readFileSync(notice, "utf8").trim(),
);
writeNotices(
  "../../jaspring-typescript/src/main/resources/META-INF/jaspring/THIRD-PARTY-LICENSES.txt",
  "jaspring-typescript.mjs",
  typescriptLicenses,
);

// The Node driver imports this same file, so it must load outside a browser without touching Node built-ins.
const smoke = await import(pathToFileURL(resolve(typescriptOutfile)).href);
const version = JSON.parse(smoke.run('{"op":"version"}'));
if (version.typescript !== versions.typescript || version.sys !== false) {
  throw new Error(
    `jaspring-typescript smoke import failed: ${JSON.stringify(version)}`,
  );
}
console.log(
  `jaspring-typescript.mjs: ${(statSync(typescriptOutfile).size / 1024 / 1024).toFixed(2)} MB, typescript ${version.typescript}`,
);

// ---------- licenses ----------

// Preserve complete licenses for packages whose code actually ships in a bundle.
function collectLicenses(metafile) {
  const licenses = new Map();
  for (const output of Object.values(metafile.outputs)) {
    for (const [input, contribution] of Object.entries(output.inputs)) {
      if (
        !input.startsWith("node_modules/") ||
        contribution.bytesInOutput === 0
      )
        continue;
      let directory = dirname(resolve(input));
      let pkg;
      while (true) {
        const manifest = join(directory, "package.json");
        if (existsSync(manifest)) {
          pkg = JSON.parse(readFileSync(manifest, "utf8"));
          if (pkg.name && pkg.version) break;
        }
        const parent = dirname(directory);
        if (parent === directory)
          throw new Error(`No package.json for bundled input ${input}`);
        directory = parent;
      }
      const key = `${pkg.name} ${pkg.version}`;
      if (licenses.has(key)) continue;
      const license = ["LICENSE", "LICENSE.txt", "LICENSE.md", "license"]
        .map((name) => join(directory, name))
        .find(existsSync);
      if (!license)
        throw new Error(`No license file for bundled package ${key}`);
      licenses.set(key, readFileSync(license, "utf8").trim());
    }
  }
  return licenses;
}

function writeNotices(path, bundleName, licenses) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(
    path,
    `Generated by tools/js-bundle. Licenses for code bundled in ${bundleName}.\n\n` +
      [...licenses]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(
          ([name, license]) =>
            `${name}\n${"=".repeat(name.length)}\n\n${license}\n`,
        )
        .join("\n"),
  );
}
